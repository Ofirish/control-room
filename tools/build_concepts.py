def validate(items):
    errs = []
    pos = {}
    for i, c in enumerate(items):
        cid, w, l = c[0], c[1], c[2]
        if cid in pos: errs.append(f"duplicate id {cid}")
        if (w, l) not in LEVELS: errs.append(f"{cid}: level {(w,l)} missing title")
        for r in c[7]:
            if r not in pos:
                errs.append(f"{cid} (W{w}L{l}) requires '{r}' which is not introduced before it")
        pos[cid] = (w, l, i)
    used_levels = {(c[1], c[2]) for c in items}
    for lv in LEVELS:
        if lv not in used_levels: errs.append(f"level {lv} has no concepts")
    # order must be non-decreasing in (world, level)
    for a, b in zip(items, items[1:]):
        if (b[1], b[2]) < (a[1], a[2]): errs.append(f"out of order: {a[0]} -> {b[0]}")
    return errs

